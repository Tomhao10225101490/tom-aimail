"""Build the reply document (.docx) that Tom AImail attaches to its reply."""

from __future__ import annotations

import io

from docx import Document


def build_docx(
    title: str,
    request_text: str,
    result_text: str,
    sender: str = "",
    attachments: tuple[str, ...] = (),
    when: str = "",
) -> bytes:
    """Return .docx bytes: title, the sender's request, and the AI result."""
    document = Document()
    document.add_heading(title or "Tom AImail result", level=1)

    meta = []
    if sender:
        meta.append(f"From: {sender}")
    if attachments:
        meta.append("Attachments: " + ", ".join(attachments))
    if when:
        meta.append(f"Date: {when}")
    if meta:
        document.add_paragraph(" · ".join(meta))

    document.add_heading("Your request", level=2)
    for paragraph in (request_text or "(no written message)").split("\n"):
        document.add_paragraph(paragraph)

    document.add_heading("Result", level=2)
    for block in result_text.split("\n"):
        line = block.rstrip()
        if line.startswith("## "):
            document.add_heading(line[3:], level=2)
        elif line.startswith("# "):
            document.add_heading(line[2:], level=1)
        elif line.startswith("- "):
            document.add_paragraph(line[2:], style="List Bullet")
        else:
            document.add_paragraph(line)

    document.add_paragraph()
    document.add_paragraph("— Generated by Tom AImail")

    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()
